import fs from 'node:fs/promises';
import path from 'node:path';
import { SITE_ORIGIN, generatedRoutes, canonicalFor } from './lib/site-routes.mjs';

const generatedMarker='<!-- generated by scripts/build-static-site.mjs; do not hand-edit -->';
const generatedDirs=['record',...generatedRoutes.map(route=>route.dir)];

const esc=value=>String(value??'').replace(/[&<>"']/g,ch=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#039;'}[ch]));
const typeFor=record=>record.kind==='summit'?'Summit':record.kind==='race'?(record.discipline==='marathon'?'Marathon':record.discipline==='trail'?'Trail race':record.discipline==='nordic'?'Nordic ski race':record.discipline==='relay'?'Relay':record.discipline==='mountain-bike'?'Mountain bike race':record.distance||'Road race'):record.kind==='outing'?(record.discipline==='nordic'?'Nordic outing':record.discipline==='mountain-bike'?(record.mtbMode==='downhill'?'Downhill MTB':'MTB outing'):'Outing'):record.kind==='event'?'Event':record.discipline==='ski-objective'?'Ski objective':record.discipline==='mountain-loop'?'Mountain loop':record.discipline==='trek'?'Trek / traverse':record.discipline==='challenge'?'Challenge':'Adventure';

const canonicalTag=url=>`<link rel="canonical" href="${esc(url)}">`;
const baseTag='<base href="/">';

function withStaticHead(html,{canonical,title,description}){
  let out=html.replace(/^\s*/,match=>`${match}${generatedMarker}`);
  out=out.replace(/<base\b[^>]*>/i,'').replace(/<link\s+rel=["']canonical["'][^>]*>/i,'');
  if(title) out=out.replace(/<title>[^<]*<\/title>/i,`<title>${esc(title)}</title>`);
  if(description){
    out=out.replace(/<meta\s+name=["']description["'][^>]*>/i,'');
    out=out.replace(/<meta\s+property=["']og:title["'][^>]*>/i,'')
      .replace(/<meta\s+property=["']og:description["'][^>]*>/i,'')
      .replace(/<meta\s+property=["']og:url["'][^>]*>/i,'');
  }
  const meta=description?`<meta name="description" content="${esc(description)}"><meta property="og:title" content="${esc(title)}"><meta property="og:description" content="${esc(description)}"><meta property="og:url" content="${esc(canonical)}">`:'';
  return out.replace(/<head>/i,`<head>${baseTag}${canonicalTag(canonical)}${meta}`);
}

for(const dir of generatedDirs) await fs.rm(dir,{recursive:true,force:true});

for(const route of generatedRoutes){
  const html=await fs.readFile(route.source,'utf8');
  const out=withStaticHead(html,{canonical:canonicalFor(route),title:null,description:null});
  await fs.mkdir(route.dir,{recursive:true});
  await fs.writeFile(path.join(route.dir,'index.html'),out.endsWith('\n')?out:`${out}\n`);
  console.log(`Generated ${route.path}/ from ${route.source} (${route.label}).`);
}

const detail=await fs.readFile('detail.html','utf8');
const publicPayload=JSON.parse(await fs.readFile('data/public-records.json','utf8'));
const records=publicPayload.records||[];
for(const record of records){
  const canonical=`${SITE_ORIGIN}/record/${encodeURIComponent(record.slug)}/`;
  const type=typeFor(record);
  const when=record.date||record.year||'';
  const where=record.location||record.region||'';
  const description=[`${record.name} — ${type}`,where,when].filter(Boolean).join(' · ')+'.';
  const title=`${record.name} | Alex Ford Adventures`;
  const out=withStaticHead(detail,{canonical,title,description});
  const dir=path.join('record',record.slug);
  await fs.mkdir(dir,{recursive:true});
  await fs.writeFile(path.join(dir,'index.html'),out.endsWith('\n')?out:`${out}\n`);
}
console.log(`Generated ${records.length} clean record documents.`);
