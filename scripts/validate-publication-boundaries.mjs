import fs from 'node:fs';
import path from 'node:path';
import { SITE_ORIGIN, siteRoutes } from './lib/site-routes.mjs';

const errors = [];

for (const field of ['key', 'path', 'source']) {
  const values = siteRoutes.map(route => route[field]).filter(Boolean);
  const duplicates = [...new Set(values.filter((value, index) => values.indexOf(value) !== index))];
  for (const value of duplicates) errors.push(`duplicate route ${field}: ${value}`);
}

for (const route of siteRoutes) {
  if (!fs.existsSync(route.source)) errors.push(`${route.key}: source is missing: ${route.source}`);
  if (route.path !== '/' && (!route.path.startsWith('/') || route.path.endsWith('/') || route.path.includes('.html'))) {
    errors.push(`${route.key}: canonical path must be clean and extensionless: ${route.path}`);
  }

  if (route.generated) {
    if (!route.dir) errors.push(`${route.key}: generated route needs an output directory`);
    if (route.dir && route.path !== `/${route.dir}`) errors.push(`${route.key}: path and generated directory disagree`);
    if (path.dirname(route.source) !== '.' || path.extname(route.source) !== '.html') errors.push(`${route.key}: generated route must use a root HTML source`);
    if (!route.browserRewrite) errors.push(`${route.key}: generated source must rewrite to its clean route in production`);

    if (route.dir) {
      const output = path.join(route.dir, 'index.html');
      if (!fs.existsSync(output)) errors.push(`${route.key}: generated output is missing: ${output}`);
      else {
        const html = fs.readFileSync(output, 'utf8');
        if (!html.includes('<!-- generated by scripts/build-static-site.mjs; do not hand-edit -->')) errors.push(`${route.key}: generated output is missing its ownership marker`);
        if (!html.includes(`<link rel="canonical" href="${SITE_ORIGIN}${route.path}">`)) errors.push(`${route.key}: generated output canonical does not match the registry`);
      }
    }
  } else if (route.dir) {
    if (route.source !== `${route.dir}/index.html`) errors.push(`${route.key}: direct route source must be its directory index`);
    if (route.path !== `/${route.dir}`) errors.push(`${route.key}: direct route path and directory disagree`);
    if (route.browserRewrite) errors.push(`${route.key}: direct route must not rewrite itself`);
  }
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

console.log(`Publication boundary validation passed for ${siteRoutes.length} registered routes.`);
