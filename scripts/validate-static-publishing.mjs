import fs from 'node:fs/promises';
import path from 'node:path';
import { SITE_ORIGIN, siteRoutes, generatedRoutes, sitemapRoutes, canonicalFor } from './lib/site-routes.mjs';

const payload=JSON.parse(await fs.readFile('data/public-records.json','utf8'));
const records=payload.records||[];
const errors=[];

if(payload.schemaVersion!==1) errors.push(`public-records schemaVersion must be 1; got ${payload.schemaVersion}`);
if(payload.recordCount!==records.length) errors.push(`public-records recordCount ${payload.recordCount} does not match ${records.length} records`);
const slugs=new Set(records.map(record=>record.slug));
if(slugs.size!==records.length) errors.push('public-records contains duplicate slugs');

for(const route of siteRoutes.filter(route=>route.dir)){
  const file=route.generated?path.join(route.dir,'index.html'):route.source;
  let html='';
  try{html=await fs.readFile(file,'utf8')}catch{errors.push(`missing public section ${file}`);continue}
  if(route.generated&&!html.includes('generated by scripts/build-static-site.mjs')) errors.push(`${file} is not marked generated`);
  if(!html.includes('<base href="/">')) errors.push(`${file} is missing root base href`);
  if(!html.includes(`<link rel="canonical" href="${canonicalFor(route)}">`)) errors.push(`${file} has wrong canonical URL`);
}

let diskSlugs=[];
try{diskSlugs=(await fs.readdir('record',{withFileTypes:true})).filter(entry=>entry.isDirectory()).map(entry=>entry.name).sort()}catch{errors.push('missing generated record directory')}
const expectedSlugs=[...slugs].sort();
if(JSON.stringify(diskSlugs)!==JSON.stringify(expectedSlugs)) errors.push(`generated record directories differ from public catalog (${diskSlugs.length} on disk vs ${expectedSlugs.length} expected)`);

for(const record of records){
  const file=path.join('record',record.slug,'index.html');
  let html='';
  try{html=await fs.readFile(file,'utf8')}catch{errors.push(`missing generated record ${file}`);continue}
  const canonical=`${SITE_ORIGIN}/record/${encodeURIComponent(record.slug)}/`;
  if(!html.includes('generated by scripts/build-static-site.mjs')) errors.push(`${file} is not marked generated`);
  if(!html.includes('<base href="/">')) errors.push(`${file} is missing root base href`);
  if(!html.includes(`<link rel="canonical" href="${canonical}">`)) errors.push(`${file} has wrong canonical URL`);
  if(!html.includes(`<title>${String(record.name).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;').replaceAll("'",'&#039;')} | Alex Ford Adventures</title>`)) errors.push(`${file} has wrong static title`);
  if(!html.includes('src="record-renderer.js"')) errors.push(`${file} does not load the record renderer`);
  if(html.includes('detail.html?record=')) errors.push(`${file} contains legacy query-route markup`);
}

const sitemap=await fs.readFile('sitemap.xml','utf8');
for(const route of sitemapRoutes){
  const url=route.path==='/'?`${SITE_ORIGIN}/`:canonicalFor(route);
  if(!sitemap.includes(`<loc>${url}</loc>`)) errors.push(`sitemap missing ${url}`);
}
for(const record of records){
  const url=`${SITE_ORIGIN}/record/${encodeURIComponent(record.slug)}/`;
  if(!sitemap.includes(`<loc>${url}</loc>`)) errors.push(`sitemap missing ${url}`);
}
const recordUrlCount=(sitemap.match(/<loc>https:\/\/adventures\.alexlford\.com\/record\//g)||[]).length;
if(recordUrlCount!==records.length) errors.push(`sitemap has ${recordUrlCount} record URLs for ${records.length} records`);

const notFound=await fs.readFile('404.html','utf8');
if(/location\.(replace|assign)|detail\.html\?record=|clean\.match\(\/\^record/.test(notFound)) errors.push('404.html still acts as the primary clean-route resolver');

if(errors.length){errors.forEach(error=>console.error(`ERROR ${error}`));process.exit(1)}
console.log(`Static publishing validation passed: ${generatedRoutes.length} generated sections + ${siteRoutes.filter(route=>route.dir&&!route.generated).length} direct sections + ${records.length} record documents.`);
